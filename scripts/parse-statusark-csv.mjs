#!/usr/bin/env node
/**
 * Parse Brandbjerg Statusark CSV → brandbjerg-arshjul.ts
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CSV_PATH =
  process.argv[2] ||
  "/home/ubuntu/.cursor/projects/workspace/uploads/AA_Statusark_2026_-_Korte_Kurser_A_ret_2026__d758.csv";
const OUT_PATH = path.join(__dirname, "../src/lib/brandbjerg-arshjul.ts");

function parseDate(d) {
  if (!d || !d.trim()) return null;
  const m = d.trim().match(/^(\d{2})\.(\d{2})\.(\d{2})$/);
  if (!m) return null;
  const yy = parseInt(m[3], 10);
  const year = yy >= 50 ? 1900 + yy : 2000 + yy;
  return `${year}-${m[2]}-${m[1]}`;
}

function parseNum(val) {
  if (!val || !val.trim()) return null;
  const cleaned = val.replace(/\./g, "").replace(",", ".");
  const n = parseFloat(cleaned);
  return Number.isFinite(n) ? Math.round(n) : null;
}

function parseIntCol(val) {
  if (!val || !val.trim()) return null;
  const n = parseInt(val.replace(/\./g, ""), 10);
  return Number.isFinite(n) ? n : null;
}

function escapeStr(s) {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, " ")
    .replace(/\r/g, "");
}

const raw = fs.readFileSync(CSV_PATH, "latin1");
const lines = raw.split(/\r?\n/);

const courses = [];
let id = 0;

for (let i = 3; i < lines.length; i++) {
  const line = lines[i];
  if (!line.trim()) continue;

  const cols = line.split(";");
  const weekRaw = cols[0]?.trim();
  const weekNumber = parseIntCol(weekRaw);
  if (!weekNumber || weekNumber < 1 || weekNumber > 53) continue;

  const title = (cols[6] || "").trim();
  if (!title || title === "-") continue;

  id++;
  const history = {};
  const yearCols = [
    [2025, 13],
    [2024, 14],
    [2023, 15],
    [2022, 16],
    [2021, 17],
    [2020, 18],
    [2019, 19],
    [2018, 20],
  ];
  for (const [year, idx] of yearCols) {
    const v = parseIntCol(cols[idx]);
    if (v != null && v > 0) history[year] = v;
  }

  const houseNote = (cols[4] || "").trim();
  const commentNote = (cols[5] || "").trim();
  const notes = [houseNote, commentNote].filter(Boolean).join(" · ");

  courses.push({
    id: `bb26-${id}`,
    weekNumber,
    startDate: parseDate(cols[1]),
    endDate: parseDate(cols[2]),
    title,
    responsible: (cols[7] || "").trim(),
    daysPattern: (cols[8] || "").trim(),
    dayCount: parseIntCol(cols[9]),
    type: (cols[10] || "").trim(),
    maxStudents: parseIntCol(cols[11]),
    budgetStudents: parseIntCol(cols[12]) ?? 0,
    notes,
    history,
  });
}

const budgetTotal = courses.reduce((s, c) => s + (c.budgetStudents || 0), 0);

function courseToTs(c) {
  const hist =
    Object.keys(c.history).length > 0
      ? `{${Object.entries(c.history)
          .sort(([a], [b]) => Number(a) - Number(b))
          .map(([y, v]) => `${y}:${v}`)
          .join(",")}}`
      : "{}";

  return `  {
    id: "${c.id}",
    weekNumber: ${c.weekNumber},
    startDate: ${c.startDate ? `"${c.startDate}"` : "null"},
    endDate: ${c.endDate ? `"${c.endDate}"` : "null"},
    title: "${escapeStr(c.title)}",
    responsible: "${escapeStr(c.responsible)}",
    daysPattern: "${escapeStr(c.daysPattern)}",
    dayCount: ${c.dayCount ?? "null"},
    type: "${escapeStr(c.type)}",
    maxStudents: ${c.maxStudents ?? "null"},
    budgetStudents: ${c.budgetStudents},
    notes: "${escapeStr(c.notes)}",
    history: ${hist},
  }`;
}

const output = `// Brandbjerg Højskole — parsed from Statusark 2026 CSV
// Generated by scripts/parse-statusark-csv.mjs — do not edit manually

export interface CourseHistory {
  [year: number]: number;
}

export interface BrandbjergPlannedCourse {
  id: string;
  weekNumber: number;
  startDate: string | null;
  endDate: string | null;
  title: string;
  responsible: string;
  daysPattern: string;
  dayCount: number | null;
  type: string;
  maxStudents: number | null;
  budgetStudents: number;
  notes: string;
  history: CourseHistory;
}

export interface AnnualPlan {
  year: number;
  targetStudents: number;
  planStatus: "udkast" | "afventer_godkendelse" | "godkendt";
  courses: BrandbjergPlannedCourse[];
  readonly?: boolean;
}

export const brandbjerg2026Courses: BrandbjergPlannedCourse[] = [
${courses.map(courseToTs).join(",\n")}
];

export const brandbjergAnnualTarget2026 = 750;
export const brandbjergBudgetTotal2026 = ${budgetTotal};

export const defaultAnnualPlans: AnnualPlan[] = [
  {
    year: 2026,
    targetStudents: 750,
    planStatus: "godkendt",
    readonly: true,
    courses: brandbjerg2026Courses,
  },
];
`;

fs.writeFileSync(OUT_PATH, output, "utf8");
console.log(`Wrote ${courses.length} courses to ${OUT_PATH}`);
console.log(`Budget total: ${budgetTotal}`);
